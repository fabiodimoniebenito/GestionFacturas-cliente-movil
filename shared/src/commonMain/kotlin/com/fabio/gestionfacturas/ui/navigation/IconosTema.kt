/** Whether the app renders dark, given the choice and the operating system's setting. */
fun PreferenciaTema.esOscuro(sistemaOscuro: Boolean): Boolean = when (this) {
    PreferenciaTema.SISTEMA -> sistemaOscuro
    PreferenciaTema.CLARO -> false
    PreferenciaTema.OSCURO -> true
}

